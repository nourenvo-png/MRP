export function sampleData(today = new Date()) {
  const cur = mKey(today);
  const asOf = dKey(today);
  let seed = 11;
  const rnd = () => { seed = (seed * 16807) % 2147483647; return seed / 2147483647; };
  const materials = [], txns = [];
  for (const [code, name, group, unit, qty, price, lead, ms] of ITEMS) {
    const key = "c:" + code.toLowerCase();
    materials.push({ key, code, name, group, unit, qty, price, lead, asOf });
    ms.forEach((tot, i) => {
      if (!tot) return;
      const mk = addM(cur, i - 6);
      const parts = 4;
      let left = tot;
      for (let j = 0; j < parts; j++) {
        const v = j < parts - 1 ? Math.round((tot / parts) * (0.7 + rnd() * 0.6)) : left;
        left -= v;
        if (v > 0) txns.push({ id: code + mk + j, key, code, name, type: "out", qty: v, date: mk + "-" + pad(3 + j * 7), manual: false, source: "بيانات مثال", sheet: "صرف" });
      }
    });
  }
  return { materials, txns };
}
